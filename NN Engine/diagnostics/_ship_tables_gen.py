# -*- coding: utf-8 -*-
"""Generate ship_tables_v3.h (the V2_SHIP_GEN = 2 compiled tables) from one exported retune arm (_retune_export.py).

  pyrun diagnostics/_ship_tables_gen.py ARM=/mnt/e/chess_data/retune/arm_h01t [OUT=ship_tables_v3.h]

Every value is written exactly as the FILE loaders would hold it (C3 / CONN / KAUF / KSB: lround of the file value; C1:
the double, since the king-distance cells stay fractional; PST: the file's ints), so the compiled ship is byte-identical
to the same arm loaded from files — the ship gate checks exactly that.
"""
import os, sys

KV = dict(a.split("=", 1) for a in sys.argv[1:] if "=" in a)
THIS = os.path.dirname(os.path.abspath(__file__))
ENGINE = os.path.dirname(THIS)
ARM = KV["ARM"]
OUT = os.path.join(ENGINE, KV.get("OUT", "ship_tables_v3.h"))
GEN = KV.get("GEN", "2")                      # 10-12: GEN=3 → *_SHIP3_* names (ship_tables_v4.h), so generations coexist


def cells(fn):
    out = []
    for line in open(os.path.join(ARM, fn)):
        if line.strip() and not line.startswith("#"):
            k, leg, _start, fitted = line.split()
            out.append((int(k), int(leg), float(fitted)))
    return out


def rnd(v):                                  # std::lround: half away from zero
    return int(v + 0.5) if v >= 0 else -int(-v + 0.5)


def int_block(name, cs):
    s = "static constexpr int %s_N = %d;\n" % (name, len(cs))
    s += "static constexpr int %s_K[%s_N] = { %s };\n" % (name, name, ", ".join(str(k) for k, _, _ in cs))
    s += "static constexpr int %s_LEG[%s_N] = { %s };\n" % (name, name, ", ".join(str(l) for _, l, _ in cs))
    s += "static constexpr int %s_V[%s_N] = { %s };\n" % (name, name, ", ".join(str(rnd(v)) for _, _, v in cs))
    return s


c1 = cells("c1.txt")
src = []
NOTE = KV.get("NOTE", "the STRUCTURAL RETUNE, hybrid fit λ0.1; self-play +56.6 · SF18 +22 · Mediocre +10 (2026-10-11)")
src.append("/* === SHIP GEN %s TABLES -- compiled in so V2_PRESET=shipped (V2_SHIP_GEN=%s) needs no file at runtime ===================\n"
           " * GENERATED by diagnostics/_ship_tables_gen.py from %s; do not hand-edit (regenerate).\n"
           " * %s.\n * Values exactly as the file loaders hold them (the ship gate checks compiled == files).\n */\n#pragma once\n"
           % (GEN, GEN, ARM, NOTE))
src.append("static constexpr int C1_SHIP" + GEN + "_N = %d;\n" % len(c1))
src.append("static constexpr int C1_SHIP" + GEN + "_K[C1_SHIP" + GEN + "_N] = { %s };\n" % ", ".join(str(k) for k, _, _ in c1))
src.append("static constexpr int C1_SHIP" + GEN + "_LEG[C1_SHIP" + GEN + "_N] = { %s };\n" % ", ".join(str(l) for _, l, _ in c1))
src.append("static constexpr double C1_SHIP" + GEN + "_V[C1_SHIP" + GEN + "_N] = { %s };\n" % ", ".join("%.4f" % v for _, _, v in c1))
for name, fn in (("KSB", "ksb.txt"), ("KFL", "kfl.txt"), ("KPROT", "kprot.txt"), ("PX", "px.txt"), ("CONN", "conn.txt")):
    src.append(int_block(name + "_SHIP" + GEN, cells(fn)))
o = [[0] * 6 for _ in range(6)]; t = [[0] * 6 for _ in range(6)]
for line in open(os.path.join(ARM, "kauf.txt")):
    if line.strip() and not line.startswith("#"):
        k, a, b, v = line.split()
        (o if k == "O" else t)[int(a)][int(b)] = rnd(float(v))
for nm, m in (("KAUF_SHIP" + GEN + "_OURS", o), ("KAUF_SHIP" + GEN + "_THEIRS", t)):
    src.append("static constexpr int %s[6][6] = {\n%s\n};\n" % (nm, ",\n".join("\t{ %s }" % ", ".join("%5d" % x for x in r) for r in m)))
vals = [int(x) for line in open(os.path.join(ARM, "pst.txt")) if not line.startswith("#") for x in line.split()]
assert len(vals) == 768, len(vals)
rows = []
for tp in range(6):
    legs = []
    for leg in (0, 1):
        legs.append("{ %s }" % ", ".join(str(v) for v in vals[tp * 128 + leg * 64: tp * 128 + leg * 64 + 64]))
    rows.append("\t{ %s }" % ", ".join(legs))
src.append("static constexpr int V2_PST_SHIP%s[6][2][64] = {\n%s\n};\n" % (GEN, ",\n".join(rows)))
open(OUT, "w").write("".join(src))
print("wrote %s: C1 %d · KSB/KFL/KPROT/PX/CONN · KAUF 6x6x2 · PST 768" % (OUT, len(c1)))
