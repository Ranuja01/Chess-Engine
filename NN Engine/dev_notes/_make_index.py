"""Regenerate the file index at the bottom of dev_notes/README.md: every doc with its title, the date it was created and
the date its content last changed (both from git, following renames). Commits whose subject starts with
"dev_notes reorganisation" only moved files or rewrote links, so they are ignored for the dates.

Usage (from anywhere, Windows or WSL python): python dev_notes/_make_index.py
"""
import os
import re
import subprocess

DN = os.path.dirname(os.path.abspath(__file__))
README = os.path.join(DN, "README.md")
BEGIN, END = "<!-- index:begin -->", "<!-- index:end -->"
SKIP_SUBJECT = "dev_notes reorganisation"
SECTIONS = [
    ("current", "Current: how the engine is now"),
    ("active", "Active: the arc in progress"),
    ("reference", "Reference: other engines"),
    ("archive", "Archive (provenance only)"),
]
# What a current/ doc actually describes, where its title alone would mislead.
NOTES = {
    "PAWN_MODEL.md": "v1 pawn system; v2's is in EVAL-V2-CURRENT-CONFIG / the rung-2 designs",
    "KING_SAFETY_MODEL.md": "v1 king safety; v2's KS-A is in EVAL-V2-CURRENT-CONFIG / the rung-1 design",
    "collinearity-why-the-eval-cannot-be-tuned.md": "measured on v1",
    "eval-architecture-degeneracy-map.md": "v1 code map",
    "UCI-BINARY-DESIGN-2026-10-19.md": "design as built 10-19; later changes in OPTIMIZATION_LOG",
    "position-bank-schema-2026-07-21.md": "tool doc",
}


def git_dates(path):
    out = subprocess.run(["git", "log", "--follow", "--date=short", "--format=%ad%x09%s", "--", path], cwd=DN,
                         capture_output=True, text=True, encoding="utf-8").stdout
    commits = [line.split("\t", 1) for line in out.splitlines() if line.strip()]
    dates = [c[0] for c in commits if not c[-1].startswith(SKIP_SUBJECT)]
    if not dates:                      # first committed by a reorganisation (it existed earlier, untracked)
        dates = [c[0] for c in commits]
    return (dates[-1], dates[0]) if dates else ("not committed", "not committed")


def title(path):
    with open(path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            if line.startswith("# "):     # links in a title would be relative to that doc, not to the README: keep the text
                return re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", line[2:].strip()).replace("|", "/")
    return ""


def rows(folder):
    out = []
    for dp, dns, fns in os.walk(os.path.join(DN, folder)):
        dns.sort()
        for f in sorted(fns):
            if not f.endswith(".md"):
                continue
            p = os.path.join(dp, f)
            rel = os.path.relpath(p, DN).replace("\\", "/")
            created, updated = git_dates(rel)
            t = title(p)
            if len(t) > 110:
                t = t[:107] + "..."
            out.append((rel, t, created, updated))
    return out


lines = [BEGIN, "", "_Generated by `_make_index.py`; do not edit by hand. Dates are git commit dates of content changes._", ""]
for folder, heading in SECTIONS:
    lines += [f"### {heading}", ""]
    if folder == "archive":
        lines += ["| file | title | created | last updated |", "|---|---|---|---|"]
    else:
        lines += ["| file | title | created | last updated | note |", "|---|---|---|---|---|"]
    for rel, t, c, u in rows(folder):
        link = f"[{rel}]({rel.replace(' ', '%20')})"
        if folder == "archive":
            lines.append(f"| {link} | {t} | {c} | {u} |")
        else:
            lines.append(f"| {link} | {t} | {c} | {u} | {NOTES.get(os.path.basename(rel), '')} |")
    lines.append("")
lines.append(END)

with open(README, encoding="utf-8") as fh:
    text = fh.read()
head = text.split(BEGIN)[0].rstrip("\n")
with open(README, "w", encoding="utf-8", newline="\n") as fh:
    fh.write(head + "\n\n" + "\n".join(lines) + "\n")
print("index rows:", sum(1 for l in lines if l.startswith("| [")))
